#!/usr/bin/env node
// =============================================================================
// db-types.mjs — generate the database's TypeScript types from the migrations
// -----------------------------------------------------------------------------
// Review C1, slice 3 (docs/design/database-snapshot-and-types.md D1, D2, D7).
// `supabase gen types` against the LOCAL stack, which is the migrations on
// this checkout applied in order, written to two byte-identical copies:
//
//   packages/db-types/database.types.ts           the app / viewer / worker
//   supabase/functions/_shared/database.types.ts  Deno (cannot reach outside
//                                                 supabase/functions at deploy)
//
//   pnpm db:types            the local stack must hold exactly the repo's
//                            migrations, same versions AND same content (it
//                            reads supabase_migrations.schema_migrations with
//                            psql, and refuses otherwise, saying why)
//   pnpm db:types --reset    rebuild the local stack first (`supabase db
//                            reset`: WIPES local data — re-seed with
//                            `pnpm playtest:seed` afterwards)
//
// Needs Docker (the local stack) and `psql` on the PATH (it reads the stack's
// migration history to compare content).
//
// Run it in the same commit as any migration — the bundle discipline.
// The header carries a sha256 of every migration file; scripts/tests/
// db-types.test.mjs recomputes it and fails when a migration changed without
// a regeneration. Honest limits (D2): CI cannot run the generator, so the stamp
// proves the file was written after the last migration change, from a stack
// whose applied migrations matched the files — not that nobody edited the
// output by hand, nor that nothing outside the migrations (hand-run SQL on the
// local stack) changed the schema; `--reset` rules out the latter. A cloud session has no Docker: it lists
// "run pnpm db:types" as a pending author action instead.
// =============================================================================

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { REPO, readMigrations, highestMigration } from './lib/migrations.mjs';

export const DB_TYPES_FILES = ['packages/db-types/database.types.ts', 'supabase/functions/_shared/database.types.ts'];

/** sha256 over every migration file, in apply order, name and bytes. */
export function migrationsHash(root = REPO) {
  const h = createHash('sha256');
  for (const { file, raw } of readMigrations(root)) h.update(`${file}\0${raw}\0`);
  return h.digest('hex');
}

export function header(root = REPO, cliVersion = '?') {
  return [
    '// GENERATED by `pnpm db:types` (scripts/db-types.mjs) — do not edit.',
    `// migrations: 0001–${highestMigration(root)}, sha256 ${migrationsHash(root)}`,
    `// generator: supabase CLI ${cliVersion}, --local --schema public`,
    '// Drift: scripts/tests/db-types.test.mjs. Design: docs/design/database-snapshot-and-types.md.',
    '',
  ].join('\n');
}

const sh = (args, opts = {}) => execFileSync('supabase', args, { cwd: REPO, encoding: 'utf8', maxBuffer: 64 << 20, ...opts });

/** Whitespace and semicolons removed: how the CLI's stored statements and a
 *  migration file are compared (the CLI splits a file into statements and
 *  drops the whitespace between them; all 106 matched this way on 2026-11-26). */
const contentKey = (text) => text.replace(/[\s;]+/g, '');

/** Why the stack's applied migrations differ from the files, or null when
 *  they are the same versions with the same CONTENT. `applied` is
 *  [{ version, statements }] from supabase_migrations.schema_migrations;
 *  `files` is [{ file, raw }]. Comparing content, not just version numbers,
 *  catches a migration edited after it was applied locally (Fable review
 *  2026-11-26: version-only, the stamp went green over the old schema). */
export function appliedMismatch(applied, files) {
  if (applied.length === 0) return 'the local stack has no applied migrations';
  const byVersion = new Map(applied.map((a) => [a.version, a.statements]));
  const missing = [], edited = [];
  for (const { file, raw } of files) {
    const v = file.slice(0, 4);
    if (!byVersion.has(v)) missing.push(v);
    else if (contentKey(byVersion.get(v)) !== contentKey(raw)) edited.push(file);
  }
  const versions = new Set(files.map((f) => f.file.slice(0, 4)));
  const extra = applied.map((a) => a.version).filter((v) => !versions.has(v));
  if (!missing.length && !extra.length && !edited.length) return null;
  return `the local stack does not hold exactly this checkout's migrations` +
    (missing.length ? `; not applied: ${missing.join(', ')}` : '') +
    (edited.length ? `; edited since it was applied: ${edited.join(', ')}` : '') +
    (extra.length ? `; applied but no file: ${extra.join(', ')}` : '') +
    (edited.length || extra.length
      ? ' — run `pnpm db:types --reset` to rebuild the stack (wipes local data)'
      : ' — run `supabase migration up --local`, or `pnpm db:types --reset` to rebuild (wipes local data)');
}

/** [{ version, statements }] from the local stack's migration history. */
function appliedOnLocalStack() {
  let env;
  try {
    env = sh(['status', '-o', 'env'], { stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    throw new Error('the local stack is not reachable — run `supabase start` first');
  }
  const url = env.match(/DB_URL="?([^"\n]+)"?/)?.[1];
  if (!url) throw new Error('`supabase status -o env` printed no DB_URL');
  const sql = "select coalesce(json_agg(json_build_object('version', version, 'statements', array_to_string(statements, E'\\n')) order by version), '[]') from supabase_migrations.schema_migrations";
  let out;
  try {
    out = execFileSync('psql', [url, '-At', '-c', sql], { encoding: 'utf8', maxBuffer: 64 << 20 });
  } catch (err) {
    throw new Error(`could not read the local migration history with psql: ${err.message}`);
  }
  return JSON.parse(out);
}

function localMatchesRepo() {
  const why = appliedMismatch(appliedOnLocalStack(), readMigrations());
  if (why) throw new Error(why);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const reset = process.argv.includes('--reset');
  if (reset) {
    console.log('supabase db reset --local (wipes local data) …');
    sh(['db', 'reset', '--local'], { stdio: 'inherit' });
  }
  localMatchesRepo();
  const cli = sh(['--version']).trim();
  const types = sh(['gen', 'types', 'typescript', '--local', '--schema', 'public'], { stdio: ['ignore', 'pipe', 'ignore'] });
  if (!types.includes('export type Database')) throw new Error('the generator returned no Database type');
  const text = header(REPO, cli) + types;
  for (const f of DB_TYPES_FILES) {
    mkdirSync(dirname(resolve(REPO, f)), { recursive: true });
    writeFileSync(resolve(REPO, f), text);
  }
  console.log(`wrote ${DB_TYPES_FILES.join(' and ')} (migrations through ${highestMigration()}${reset ? ', after a reset' : ''})`);
  if (reset) console.log('local data was wiped: `pnpm playtest:seed` re-seeds it');
}
